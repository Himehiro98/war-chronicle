/** 本文データにアップデートを重ねる */
export function applyContentUpdates(base: Record<string, TabContent>): Record<string, TabContent> {
  const out = { ...base };
  for (const [id, p] of Object.entries(CONTENT_UPDATES)) {
    const c = out[id];
    if (!c) continue;
    out[id] = {
      ...c,
      digest: { ...c.digest, ...(p.digest ?? {}) },
      detail: {
        ...c.detail,
        ...(p.detail?.title ? { title: p.detail.title } : {}),
        ...(p.detail?.kicker ? { kicker: p.detail.kicker } : {}),
        ...(p.detail?.lead ? { lead: p.detail.lead } : {}),
        sections: [...c.detail.sections, ...(p.detail?.appendSections ?? [])],
      },
      legacy: p.legacy ?? c.legacy,
      structure: p.structureSummary ? { ...c.structure, summary: p.structureSummary } : c.structure,
    };
  }
  return out;
}
